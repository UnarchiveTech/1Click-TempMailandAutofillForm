/**
 * Shared i18n engine for non-Svelte contexts (background, content scripts,
 * utilities).
 *
 * The MV3 service worker is bundled as a single self-contained file, so any
 * locale dictionary it imports - even via dynamic import() - is inlined into
 * background.js. To avoid duplicating all 8 full UI dictionaries
 * (1,355,253 bytes) into the worker, the engine is built as a factory parameterized by the
 * dictionaries it should load:
 *
 *   - `@/utils/i18n/i18n-utils.ts`       → full UI dictionaries (UI + utilities)
 *   - `@/utils/i18n/i18n-background.ts`  → minimal per-language sets generated by
 *                                     scripts/generate-background-locales.ts
 *                                     (background + content-script keys only)
 *
 * Both wrappers expose the exact same API, so call sites can switch between
 * them with a one-line import change.
 *
 * Locale strategy: English is statically imported as the universal fallback
 * so tSync() always works - even if dynamic imports fail at runtime. The
 * other locales are dynamically imported and code-split, so only the active
 * locale + English are loaded at startup.
 *
 * IMPORTANT: Language is stored as both `preferredLanguage` (LanguageSwitcher legacy) and
 * `locale` (canonical). Always resolve via resolveStoredLocale().
 */

import { browser } from 'wxt/browser';
import { logError } from '../logger.js';
import { writeWithRetry } from '../storage/storage-write.js';

export type LocaleTree = Record<string, unknown>;

export interface I18nModuleInput<C extends readonly string[]> {
  /** Supported language codes shipped in the extension (en first). */
  codes: C;
  /** English dictionary (static import - the universal fallback). */
  en: LocaleTree;
  /**
   * Dynamic loaders for non-English locales. Using dynamic import() here
   * means Vite creates a separate chunk per locale and only loads the
   * requested one.
   */
  loaders: Record<Exclude<C[number], 'en'>, () => Promise<unknown>>;
}

/** Normalize Vite/JSON module shapes (`default` wrapper or plain object). */
function asTree(mod: unknown): LocaleTree {
  if (!mod || typeof mod !== 'object') return {};
  const m = mod as { default?: LocaleTree };
  if (m.default && typeof m.default === 'object') return m.default;
  return mod as LocaleTree;
}

/**
 * Substitute {var} placeholders in a string with values from a record.
 */
function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match
  );
}

function lookupInTree(translations: LocaleTree, key: string): string | undefined {
  const keys = key.split('.');
  let value: unknown = translations;
  for (const k of keys) {
    if (value && typeof value === 'object' && k in value) {
      value = (value as LocaleTree)[k];
    } else {
      return undefined;
    }
  }
  return typeof value === 'string' ? value : undefined;
}

/** Hardcoded English fallbacks so UI never flashes raw keys like `time.hoursAgo`. */
const EN_SYNC_FALLBACKS: Record<string, string> = {
  'time.justNow': 'Just now',
  'time.secondsAgo': '{n} second ago',
  'time.secondsAgoPlural': '{n} seconds ago',
  'time.minutesAgo': '{n} minute ago',
  'time.minutesAgoPlural': '{n} minutes ago',
  'time.hoursAgo': '{n} hour ago',
  'time.hoursAgoPlural': '{n} hours ago',
  'time.daysAgoLong': '{n} days ago',
  'time.today': 'Today',
  'time.yesterday': 'Yesterday',
  'time.never': 'Never',
  'time.expired': 'Expired',
};

/**
 * Build a translation module bound to a specific set of dictionaries.
 * See the module comment for why this is a factory instead of a singleton.
 */
export function createI18nModule<C extends readonly string[]>(input: I18nModuleInput<C>) {
  const SUPPORTED_LOCALES: C = input.codes;

  // Cache for loaded translations
  const translationCache = new Map<string, LocaleTree>();

  /** Last known locale for tSync when locale arg is omitted. */
  let cachedLocale = 'en';

  const EN_TREE: LocaleTree = asTree(input.en);

  /** Map any browser/storage locale string to a supported 2-letter code. */
  function mapToSupportedLocale(raw: string | null | undefined): string {
    const code = String(raw || '')
      .trim()
      .split(/[-_]/)[0]
      .toLowerCase();
    if (code && (code === 'en' || code in input.loaders)) return code;
    return 'en';
  }

  /**
   * Resolve the user's language from storage (or a storage snapshot).
   * Priority: preferredLanguage → locale → page/navigator language → en
   */
  function resolveStoredLocale(snap?: { locale?: string; preferredLanguage?: string }): string {
    const raw = snap?.preferredLanguage || snap?.locale || '';
    if (raw) return mapToSupportedLocale(raw);
    return '';
  }

  /**
   * Get the current locale from storage (extension preference).
   * Priority: preferredLanguage → locale → page/navigator language → en
   */
  async function getStoredLocaleAsync(): Promise<string> {
    try {
      const result = (await browser.storage.local.get(['locale', 'preferredLanguage'])) as {
        locale?: string;
        preferredLanguage?: string;
      };
      const stored = resolveStoredLocale(result);
      if (stored) return stored;

      // Page / browser language when user never set a preference
      if (typeof document !== 'undefined') {
        const docLang = document.documentElement?.lang || '';
        const navLang = typeof navigator !== 'undefined' ? navigator.language : '';
        const fromPage = mapToSupportedLocale(docLang || navLang);
        if (fromPage && (docLang || navLang)) {
          return fromPage;
        }
      } else if (typeof navigator !== 'undefined' && navigator.language) {
        return mapToSupportedLocale(navigator.language);
      }
      return 'en';
    } catch {
      /* ignore */
      return 'en';
    }
  }

  /**
   * Persist language preference under both storage keys used in the codebase.
   */
  async function persistLocale(langCode: string): Promise<string> {
    const code = mapToSupportedLocale(langCode);
    cachedLocale = code;
    try {
      await writeWithRetry({ locale: code, preferredLanguage: code });
    } catch (e) {
      logError('Failed to persist locale', e);
    }
    return code;
  }

  /**
   * Load translations for a specific locale (dynamic import - only loads
   * the requested locale chunk, not all locales).
   */
  async function loadTranslations(locale: string): Promise<LocaleTree> {
    const code = mapToSupportedLocale(locale);

    // English is always available via static import
    if (code === 'en') {
      if (!translationCache.has('en')) {
        translationCache.set('en', EN_TREE);
      }
      return translationCache.get('en') ?? EN_TREE;
    }

    // Check cache first
    if (translationCache.has(code)) {
      return translationCache.get(code) ?? {};
    }

    // Ensure English fallback is cached
    if (!translationCache.has('en')) {
      translationCache.set('en', EN_TREE);
    }

    try {
      const loader = input.loaders[code as Exclude<C[number], 'en'>];
      if (!loader) {
        return EN_TREE;
      }
      const mod = await loader();
      const tree = asTree(mod);
      translationCache.set(code, tree);
      return tree;
    } catch (e) {
      logError(`Failed to load locale pack for ${code}`, e);
      return EN_TREE;
    }
  }

  /**
   * Get a translated string by key path (e.g., "errors.apiCallFailed")
   * Supports nested keys with dot notation and {var} interpolation.
   */
  async function t(
    key: string,
    vars?: Record<string, string | number>,
    locale?: string
  ): Promise<string> {
    const targetLocale = mapToSupportedLocale(locale || (await getStoredLocaleAsync()));
    cachedLocale = targetLocale;
    const translations = await loadTranslations(targetLocale);

    let found = lookupInTree(translations, key);
    if (found === undefined && targetLocale !== 'en') {
      found = lookupInTree(await loadTranslations('en'), key);
    }
    if (found !== undefined) return interpolate(found, vars);
    return key;
  }

  /**
   * Get a translated string synchronously (uses cached translations).
   */
  function tSync(key: string, vars?: Record<string, string | number>, locale?: string): string {
    const targetLocale = mapToSupportedLocale(locale || cachedLocale || 'en');
    const translations =
      translationCache.get(targetLocale) ||
      (targetLocale !== 'en' ? translationCache.get('en') : undefined);

    if (translations) {
      const found = lookupInTree(translations, key);
      if (found !== undefined) return interpolate(found, vars);
    }

    // English is always statically available - consult EN_TREE directly (not only
    // via the cache) so tSync never returns a raw key like `omnibox.defaultSuggestion`
    // before preloadTranslations has populated the cache (e.g. context-menu or
    // omnibox copy rendered at service-worker startup).
    const enFound = lookupInTree(EN_TREE, key);
    if (enFound !== undefined) return interpolate(enFound, vars);

    const fallback = EN_SYNC_FALLBACKS[key];
    if (fallback) return interpolate(fallback, vars);

    return key;
  }

  /** Remember the active locale for synchronous helpers. */
  function setCachedLocale(locale: string): void {
    cachedLocale = mapToSupportedLocale(locale);
  }

  /** Read the active locale for synchronous formatters that accompany tSync. */
  function getCachedLocale(): string {
    return cachedLocale;
  }

  /** Preload translations for a locale (call this on startup) */
  async function preloadTranslations(locale: string): Promise<void> {
    const code = mapToSupportedLocale(locale);
    cachedLocale = code;
    if (code !== 'en') {
      await loadTranslations('en');
    }
    await loadTranslations(code);
  }

  /** Clear translation cache (useful for locale changes) */
  function clearTranslationCache(): void {
    translationCache.clear();
  }

  // Keep content/background UIs in sync when user changes language
  try {
    browser.storage.onChanged.addListener((changes, area) => {
      if (area !== 'local') return;
      if (!changes.locale && !changes.preferredLanguage) return;
      const nextRaw =
        (changes.preferredLanguage?.newValue as string | undefined) ||
        (changes.locale?.newValue as string | undefined) ||
        'en';
      const next = mapToSupportedLocale(nextRaw);
      clearTranslationCache();
      setCachedLocale(next);
      void preloadTranslations(next).catch((e: unknown) =>
        logError('Failed to reload translations after locale change', e)
      );
    });
  } catch {
    /* storage may be unavailable in some test contexts */
  }

  // Self-warm from the stored preference. The service worker preloads
  // explicitly at startup (background/index.ts) and UI surfaces warm the
  // full-dictionary engine (i18n.ts / AppLayout), but this engine instance
  // previously stayed on the 'en' fallback in UI contexts until the next
  // locale CHANGE - so tSync-based helpers (time-format, storageMonitor's
  // formatBytes) rendered English for users whose preference was set in an
  // earlier session. Resolves from storage (or navigator when unset); no-op
  // when storage is unavailable (tests keep the en fallback).
  void (async () => {
    try {
      await preloadTranslations((await getStoredLocaleAsync()) || 'en');
    } catch {
      /* storage unavailable - keep the en fallback */
    }
  })();

  return {
    SUPPORTED_LOCALES,
    mapToSupportedLocale,
    resolveStoredLocale,
    getStoredLocaleAsync,
    persistLocale,
    t,
    tSync,
    setCachedLocale,
    getCachedLocale,
    preloadTranslations,
    clearTranslationCache,
  };
}
