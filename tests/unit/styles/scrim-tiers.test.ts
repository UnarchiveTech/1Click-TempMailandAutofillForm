/**
 * Scrim tiers - one home for backdrop opacities.
 *
 * `src/styles.css`'s `@theme` block carries the named tiers:
 *
 *   --color-md-scrim-basic  32% - lightweight, dismissible surfaces
 *     (command palette, keyboard cheat sheet, inline modal shell)
 *   --color-md-scrim-modal  40% - modal dialogs, bottom sheets, blocking
 *     drawers and the product tour's guided-focus dim
 *
 * Components consume `bg-md-scrim-basic` / `bg-md-scrim-modal` (or the raw
 * `var(--color-md-scrim-*)` where a class attribute can't carry it); they never
 * re-derive `color-mix(... var(--md-scrim) ...)` or write a per-call-site
 * opacity modifier. This suite pins the tier definitions to their canonical
 * percentages and scans `src/` for raw hand-tuned scrims so the /30-/55
 * spread cannot return one call site at a time.
 *
 * The definitions deliberately live in styles.css and NOT in
 * `src/styles/theme.css`, which is REGENERATED by scripts/generate-theme.ts and
 * would silently drop hand-added tokens (same rule as the pressed-container
 * tokens). A test below locks that choice in.
 */

import { describe, expect, test } from 'bun:test';
import { readdirSync } from 'node:fs';
import { extname, join } from 'node:path';
import { PROJECT_ROOT } from '../helpers/project-root';
import { readSource } from '../helpers/theme-contrast';

const STYLES_CSS = 'src/styles.css';
const THEME_CSS = 'src/styles/theme.css';

/** Tier → canonical color-mix percentage against --md-scrim. */
const CANONICAL_PERCENTS = { basic: 32, modal: 40 } as const;

const stylesCss = readSource(STYLES_CSS);
const themeCss = readSource(THEME_CSS);

/** The tier's declared percentage, parsed from styles.css. */
function tierPercent(tier: keyof typeof CANONICAL_PERCENTS): number {
  const match = stylesCss.match(
    new RegExp(
      `--color-md-scrim-${tier}:\\s*color-mix\\(in srgb,\\s*var\\(--md-scrim,\\s*#000\\)\\s*(\\d+)%`
    )
  );
  if (!match) {
    throw new Error(`styles.css no longer derives --color-md-scrim-${tier} from var(--md-scrim)`);
  }
  return Number(match[1]);
}

describe('scrim tier tokens', () => {
  test('each tier is defined exactly once, inside the styles.css @theme block', () => {
    const themeStart = stylesCss.indexOf('@theme {');
    expect(themeStart).toBeGreaterThan(-1);
    const themeBlock = stylesCss.slice(themeStart, stylesCss.indexOf('\n}', themeStart));

    for (const tier of Object.keys(CANONICAL_PERCENTS)) {
      const decl = `--color-md-scrim-${tier}:`;
      expect(stylesCss.split(decl)).toHaveLength(2); // exactly one definition
      expect(themeBlock).toContain(decl); // ...and it is in @theme
      // theme.css is regenerated; a hand-added token there would be dropped on
      // the next `bun run generate-theme` - the definition must stay out of it.
      expect(themeCss).not.toContain(decl);
    }
  });

  test('each tier mixes the --md-scrim token at its canonical opacity', () => {
    expect(tierPercent('basic')).toBe(CANONICAL_PERCENTS.basic);
    expect(tierPercent('modal')).toBe(CANONICAL_PERCENTS.modal);
  });

  test('the modal tier is at least as strong as the basic tier', () => {
    expect(tierPercent('modal')).toBeGreaterThanOrEqual(tierPercent('basic'));
  });
});

// ── The ratchet: components consume the named tiers ─────────────────────────

const SCANNED_EXTENSIONS = new Set(['.svelte', '.ts', '.js', '.css']);
/** The one home of the tier definitions - everything else in src/ is a consumer. */
const EXEMPT_FILES = new Set([STYLES_CSS]);

/**
 * A dim-scrim opacity modifier on any scrim color: `bg-md-scrim/40`,
 * `bg-md-scrim-basic/50`, bracket-alpha forms too. Modifiers ≥ 80 are excluded
 * on purpose: they are near-SOLID fills (AppShell's non-dismissible
 * viewport-restriction blocker), a different visual device than the tunable
 * dim tiers - folding them into a dim tier would make the blocker translucent.
 * The number is end-anchored so a ≥80 two-digit value (`/95`) never matches via
 * its first digit.
 */
const RAW_SCRIM_OPACITY = /-md-scrim(?:-basic|-modal)?\/(?:[0-7]\d?(?!\d)|\[0?\.[0-7])/;
/** A hand-rolled mix of the base token, bypassing the tiers. */
const HAND_ROLLED_SCRIM_MIX = /color-mix\([^;]*var\(--md-scrim/;

function* walk(dir: string): Generator<string> {
  for (const entry of readdirSync(join(PROJECT_ROOT, dir), { withFileTypes: true })) {
    const rel = `${dir}/${entry.name}`;
    if (entry.isDirectory()) {
      if (entry.name !== 'node_modules') yield* walk(rel);
    } else if (SCANNED_EXTENSIONS.has(extname(entry.name))) {
      yield rel;
    }
  }
}

function scrimViolations(relPath: string): string[] {
  const source = readSource(relPath);
  const found: string[] = [];
  if (RAW_SCRIM_OPACITY.test(source))
    found.push('raw scrim opacity modifier (use bg-md-scrim-basic / bg-md-scrim-modal)');
  if (HAND_ROLLED_SCRIM_MIX.test(source))
    found.push('hand-rolled color-mix on --md-scrim (consume the tier token instead)');
  return found;
}

describe('scrim tiers ratchet', () => {
  const consumers = [...walk('src')].filter((f) => !EXEMPT_FILES.has(f));

  test('no raw scrim opacity or hand-rolled mix outside the definition home', () => {
    const offenders = consumers
      .map((file) => ({ file, reasons: scrimViolations(file) }))
      .filter(({ reasons }) => reasons.length > 0)
      .map(({ file, reasons }) => `${file}: ${reasons.join('; ')}`);
    expect(offenders).toEqual([]);
  });

  test('both tiers have at least one consumer (no dead tier)', () => {
    const sources = consumers.map((file) => readSource(file));
    const uses = (tier: keyof typeof CANONICAL_PERCENTS) =>
      sources.filter((s) =>
        new RegExp(`bg-md-scrim-${tier}\\b|var\\(--color-md-scrim-${tier}\\)`).test(s)
      ).length;
    expect(uses('basic')).toBeGreaterThan(0);
    expect(uses('modal')).toBeGreaterThan(0);
  });
});
